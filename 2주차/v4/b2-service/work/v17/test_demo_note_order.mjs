import assert from'node:assert/strict';
import{orderedNotes,prepareNotes,insertNote,deleteNote,followupText}from'./demo_note_order.mjs';
let b={summary:[{text:'논의'}],decisions:[{text:'결정'}],candidates:[{id:'a',title:'후속 A'},{id:'b',title:'후속 B'}]};
const texts=b=>orderedNotes(b).map(r=>r.item.text||r.item.title);
b=insertNote(b,{key:'candidates',index:0},'manual').bundle;b.summary[1].text='선택 아래';
assert.deepEqual(texts(b),['논의','결정','후속 A','선택 아래','후속 B']);
b=prepareNotes(JSON.parse(JSON.stringify(b)));
b=insertNote(b,null,'end').bundle;b.summary[2].text='마지막';
b=deleteNote(b,'summary',0);
assert.deepEqual(texts(JSON.parse(JSON.stringify(b))),['결정','후속 A','선택 아래','후속 B','마지막']);
b=insertNote(b,{key:'decisions',index:0},'between').bundle;b.summary[2].text='결정 아래';
assert.deepEqual(texts(b),['결정','결정 아래','후속 A','선택 아래','후속 B','마지막']);
console.log('PASS: insert below selected item across categories, append without selection, delete and reload preserve editorial order.');
assert.equal(followupText({title:'사양서를 개정한다.',description:'사양서를 개정한다.'}),'사양서를 개정한다.');
assert.equal(followupText({title:'사양서를  개정한다.',description:'사양서를\n개정한다.'}),'사양서를\n개정한다.');
assert.equal(followupText({title:'사양서 개정',description:'변경 폭 520 mm를 반영하고 고객에게 공유한다.'}),'사양서 개정\n변경 폭 520 mm를 반영하고 고객에게 공유한다.');
assert.equal(followupText({title:'도면 제출'}),'도면 제출');
assert.equal(followupText({description:'기존 구멍은 유지한다.'}),'기존 구멍은 유지한다.');
console.log('PASS: identical follow-up title is shown once; distinct conditions, line breaks and single-field records are retained.');
