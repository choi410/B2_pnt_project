"""Open issues (미결 사항) in the minutes and what later meetings did with them.

Rule-based and computed when the workspace is read, so older analyses get it too and
nothing is generated by the model:
  1. extract  - sentences left undecided in a meeting: the "추가 확인" section, and any
                sentence saying it is undecided (미정, 정하지 않았다, 보류, 협의하기로 ...).
                A list in the pending section ("A, B 및 C.") becomes one issue per item.
                Issues about the same subject in one meeting are merged.
  2. resolve  - later meetings of the same project are read in date order. A later line
                about the same subject that is no longer undecided, or a later agreed or
                withdrawn change record about it, makes the issue a resolution *candidate*;
                a later line that is still undecided marks it as discussed again.
A person still judges a candidate: the screen shows the later sentence and its meeting.
"""
import re

from work.v3.review_tier import _SECTIONS

VERSION = 'open-1'

OPEN = re.compile(r'미정|미확정|추후\s*(결정|논의|협의|검토|확정)|확인\s*필요|결정\s*예정|재검토|더\s*검토|추가\s*검토|'
                  r'정하지\s*않|결정하지\s*않|확정하지\s*않|승인하지\s*않|합의하지\s*않|확인되지\s*않|검토\s*중|'
                  r'다음\s*(회의|협의)에서|별도\s*(회의|협의)|협의하기로|검토하기로|다시\s*협의|보류')
# Words that say an issue is open, or are too common to tell subjects apart.
_STOP = {'미정', '미확정', '담당자', '담당', '기한', '일정', '이번', '회의', '다음', '별도', '협의', '결정', '확정', '아직',
         '여부', '예정', '추후', '검토', '재검토', '따로', '추가', '확인', '필요', '상세', '세부', '최종', '방식', '기준',
         '요청', '고객', '고객사', '이후', '진행', '정리', '적용', '변경', '보류', '유지', '기존', '함께', '관련', '내용',
         '항목', '사항', '문제', '부분', '경우', '다만', '자체', '원래', '이걸', '이것', '그것', '아님', '없어', '있어',
         '없음', '있음', '들어오', '결과', '공유', '후속', '회의명', '프로젝트', '회의일', '참석자', '작성자',
         '이다', '한다', '했다', '하기로', '하기', '않았다', '않는다', '않음', '않았', '정한다', '정하지', '결정하지',
         '확정하지', '승인하지', '합의하지', '확인되지', '다시', '현재', '우선'}
_PARTICLE = re.compile(r'(으로|에서|까지|부터|이며|이고|하고|이다|에게|와의|과의|은|는|이|가|을|를|의|와|과|도|만|로|에)$')
_VERBISH = re.compile(r'(한|할|하기|하며|하다|하고|해서|하여|했다|함|인데|어서|아서|하면|되면|려던|겠다|는지|을지|할지|바꿀지|이며|혀서|여서|워서|된)$')
_UNITS = {'mm', 'cm', 'm', 'km', 'kg', 'g', 'rpm', 'kw', 'w', 'v', 'a', 'min', 'sec', 'ms', 's', 'h', 'pm', 'qa', 'pd', 'rev'}
_LEAD = re.compile(r'^[^:：]{1,24}[:：]\s*')
_END = re.compile(r'[.!?。]\s*$|[다함음됨임]\s*$|\)\s*$|\d\s*$')
_ITEM = re.compile(r'^\s*(\d+[.)]|[-•·※]|[A-Z]\d*[.)]\s)')
_META = re.compile(r'^(회의명|회의\s*일시|회의일|일시|일자|프로젝트|프로젝트명|참석|참석자|작성|작성자|작성일|장소|MEETING|회의록$)')


def keywords(text, names=()):
    """Subject words of a sentence: speaker label, particles and endings stripped,
    open/common words, units and attendee names dropped."""
    out = []
    for raw in re.findall(r'[가-힣]+|[A-Za-z]+|\d+(?:\.\d+)?', _LEAD.sub('', str(text or ''))):
        word = raw
        if re.match(r'[가-힣]', word):
            for _ in range(2):
                stripped = _PARTICLE.sub('', word)
                if len(stripped) >= 2:
                    word = stripped
            if len(word) >= 3 and _VERBISH.search(word):
                continue
            if len(word) < 2:
                continue
        if word in _STOP or word in names or word.casefold() in _UNITS or OPEN.fullmatch(word) or \
                re.search(r'(하지|되지|않|했|한다|하겠|하자|이었)', word):
            continue
        if word not in out:
            out.append(word)
    return out


def _names(lines):
    """Attendee names, from the attendee line, so a person does not make two issues alike."""
    for line in lines or []:
        text = str(line.get('text') or '')
        if re.search(r'참석', text):
            return set(re.findall(r'[가-힣]{2,4}', re.sub(r'^.*?참석[^:：|]*[:：|]?', '', text, count=1)))
    return set()


def _sections(lines):
    """Line id -> section, as review_tier.sections, with the agenda kept apart from the discussion."""
    current = None; out = {}
    for line in lines or []:
        text = re.sub(r'^[\s\d.)\]\-•·#|]+', '', str(line.get('text') or '')).strip()
        if 0 < len(text) <= 20:
            kind = 'agenda' if re.search(r'안건', text) else next((k for k, p in _SECTIONS if p.search(text)), None)
            if kind:
                current = kind; out[line['id']] = 'header'; continue
        out[line['id']] = current
    return out


def _sentences(lines, where):
    """[(text, [line ids], section)], joining a sentence broken across two lines.
    Header-block lines (회의명:, 참석:, ...) and, when the minutes have sections, lines
    before the first section are left out."""
    sectioned = any(v not in (None, 'header') for v in where.values())
    groups = []
    for line in lines or []:
        section = where.get(line['id'])
        text = re.sub(r'^[A-Z]{1,2}\d+:\s*', '', str(line.get('text') or '').strip())  # spreadsheet cell label
        if section == 'header' or not text or _META.search(text) or (sectioned and section is None):
            continue
        # A numbered or bulleted line starts a new item even if the one before has no ending.
        if groups and groups[-1][2] == section and not _END.search(groups[-1][0]) and not _ITEM.match(text):
            groups[-1] = (groups[-1][0] + ' ' + text, groups[-1][1] + [line['id']], section)
        else:
            groups.append((text, [line['id']], section))
    out = []
    for text, ids, section in groups:
        for part in re.split(r'(?<=[.!?])\s+', text):
            part = part.strip()
            if part:
                out.append((part, ids, section))
    return out


def _list_items(text):
    """'A, B 및 C.' -> ['A', 'B', 'C'] for a pending-section line without a verb."""
    body = re.sub(r'[.。]\s*$', '', text)
    if OPEN.search(body) or re.search(r'[다함음]$', body):
        return [text]
    parts = [p.strip() for p in re.split(r',|·|\s및\s', body) if p.strip()]
    return parts if len(parts) > 1 else [text]


def _same_word(a, b):
    """`a` appears in `b`, or `b` is `a` short of one trailing syllable (작업통로 / 작업통)."""
    return a in b or (b in a and len(a) - len(b) <= 1)


def _covers(small, large):
    """Every subject word of `small` is in `large`."""
    return bool(small) and all(any(_same_word(a, b) for b in large) for a in small)


def _likeness(a, b):
    """0..1: how far two subjects are the same. 1 when one's words all lie within the other's;
    otherwise the shared share of the shorter one, counted only from two shared words
    ("조치 전후 사진의 촬영 범위" / "사진 촬영 범위와 제출 방식")."""
    if _covers(a, b) or _covers(b, a):
        return 1.0
    shared = sum(any(_same_word(x, y) for y in b) for x in a)
    ratio = shared / max(1, min(len(a), len(b)))
    return ratio if shared >= 2 and ratio >= 0.6 else 0.0


def _still_open(text):
    """An undecided wording that describes the present, not the past
    ("지난번에 검토중이던 운전 속도 건" looks back at something since settled)."""
    return any(not re.match(r'\s*(이던|였던|이었던|했던|하던|됐던|되었던)', text[m.end():]) for m in OPEN.finditer(text))


def extract(lines):
    """Open issues of one meeting: [{id, text, evidence, section, keywords}]."""
    where = _sections(lines)
    names = _names(lines)
    found = []
    for text, ids, section in _sentences(lines, where):
        if section == 'pending':
            parts = _list_items(text)
        elif section != 'agenda' and _still_open(text):
            parts = [text]
        else:
            continue
        for part in parts:
            words = keywords(part, names)
            if not words:
                # "담당자와 검토 기한은 미정이다." belongs to the sentence before it.
                if found and found[-1]['evidence'][-1] in ids:
                    found[-1]['text'] += ' ' + part
                continue
            found.append({'text': part, 'evidence': list(ids), 'section': section, 'keywords': words,
                          'full': part == text})
    # Merge issues on the same subject. Each sentence joins the issue whose first sentence
    # it is most like; comparing with the first sentence only keeps a sentence that lists
    # several subjects ("치수, 점검문 위치 및 검사 합격 기준") from chaining them into one.
    groups = []
    for issue in found:
        scores = [_likeness(issue['keywords'], g[0]['keywords']) for g in groups]
        best = max(range(len(groups)), key=lambda i: scores[i], default=None)
        if best is not None and scores[best] > 0:
            groups[best].append(issue)
        else:
            groups.append([issue])
    out = []
    for group in groups:
        # A full sentence that says it is undecided reads best; then the pending section, then the first.
        lead = max(group, key=lambda x: (bool(x['full'] and OPEN.search(x['text'])), x['section'] == 'pending', -group.index(x)))
        evidence = list(dict.fromkeys(i for x in group for i in x['evidence']))
        # Each merged sentence keeps its own subject; one-word subjects only when nothing longer.
        subjects = [x['keywords'] for x in group if len(x['keywords']) > 1] or [x['keywords'] for x in group]
        subjects = [list(k) for k in dict.fromkeys(tuple(k) for k in subjects)]
        out.append({'id': evidence[0] + ':' + str(len(out)), 'text': lead['text'], 'evidence': evidence,
                    'section': lead['section'], 'keywords': lead['keywords'], 'subjects': subjects})
    return out


def _matches(words, text, names=()):
    """True when a sentence is about the issue: at least half of its subject words,
    and two of them (one, for a one-word subject)."""
    seen = keywords(text, names)
    hit = sum(any(_same_word(w, x) for x in seen) for w in words)
    return hit >= min(2, len(words)) and hit * 2 >= len(words)


def resolve(issue, later, changes=()):
    """later   : [meeting] of the same project after the issue's meeting, in date order
    changes : change records of those meetings (not excluded)
    Returns {'status': 'open'|'discussed'|'resolved', 'by': {...} or None}; the latest
    meeting that mentions the subject decides."""
    subjects = issue.get('subjects') or [issue['keywords']]
    about = lambda text, names=(): any(_matches(words, text, names) for words in subjects)
    single = all(len(words) == 1 for words in subjects)
    status = {'status': 'open', 'by': None}
    for m in later:
        where = _sections(m.get('lines'))
        names = _names(m.get('lines'))
        hits = [(t, ids, s) for t, ids, s in _sentences(m.get('lines'), where)
                if about(t, names)]
        # An agenda item or a follow-up task brings the subject up again but does not answer it;
        # a one-word subject needs a decision line.
        settled = [h for h in hits if not OPEN.search(h[0]) and h[2] not in ('agenda', 'followup')
                   and (not single or h[2] == 'decision')]
        agreed = [e for e in changes if e.get('meeting_id') == m['id'] and e.get('business_state') in ('확정', '철회')
                  and e.get('review_state') != '제외' and about(str(e.get('title')) + ' ' + str(e.get('after')))]
        base = {'meeting_id': m['id'], 'meeting_title': m.get('title'), 'date': m.get('date')}
        if settled:
            text, ids, _ = next((h for h in settled if h[2] == 'decision'), settled[0])
            status = {'status': 'resolved', 'by': {**base, 'text': text, 'evidence': ids}}
        elif agreed:
            e = agreed[0]
            status = {'status': 'resolved', 'by': {**base, 'text': f"{e.get('title')}: {e.get('after')} ({e.get('business_state')})",
                                                   'change_id': e.get('id')}}
        elif hits:
            status = {'status': 'discussed', 'by': {**base, 'text': hits[0][0], 'evidence': hits[0][1]}}
    return status


def attach(meetings, changes):
    """Set m['open_issues'] on each meeting. meetings: the shown (not deleted) meetings;
    changes: the shown change records. A failure leaves an empty list."""
    order = lambda m: (m.get('date') or '', m.get('created_at') or '')
    by_project = {}
    for m in meetings:
        by_project.setdefault(m.get('project_id'), []).append(m)
    for group in by_project.values():
        group.sort(key=order)
        for i, m in enumerate(group):
            try:
                later = [x for x in group[i + 1:] if order(x) > order(m)]
                ids = {x['id'] for x in later}
                mine = [e for e in changes if e.get('meeting_id') in ids]
                m['open_issues'] = [{**issue, **resolve(issue, later, mine)} for issue in extract(m.get('lines'))]
            except Exception:
                m['open_issues'] = []
